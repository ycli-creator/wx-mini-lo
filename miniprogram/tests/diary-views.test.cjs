const assert = require('node:assert/strict')
const { diaryStatistics, diaryYear, diaryMemories, diaryFeed } = require('../utils/diary-views.ts')
const entry = (id, date, patch = {}) => ({ id, date, version: 1, time: '12:00', title: '', body: '文字\n 日记', mood: '', weather: '', location: '', category: '', tags: [], favorite: false, pinned: false, deleted: false, draft: false, createdAt: date+'T12:00:00Z', updatedAt: date+'T12:00:00Z', ...patch })
const image = (id) => ({ id, src: `/assets/${id}.svg`, width: 100, height: 100 })
async function run() {
  const rows = [
    entry('today-a', '2026-10-27', { images: [image('today')], mood: '开心' }),
    entry('today-b', '2026-10-27', { images: [image('another')], time: '18:00', weather: '晴' }),
    entry('yesterday', '2026-10-26'), entry('gap', '2026-10-24'),
    entry('anniversary', '2025-10-27'), entry('older-anniversary', '2024-10-27'),
    entry('random-one', '2025-08-12'), entry('random-two', '2024-02-29'),
    entry('hidden', '2020-01-01', { hidden: true, images: [image('private')], body: '不能出现' }),
    entry('draft', '2019-01-01', { draft: true, body: '不能出现' }),
    entry('trash', '2018-01-01', { deleted: true, body: '不能出现' }),
  ]
  const stats = diaryStatistics(rows, '2026-10-27')
  assert.equal(stats.total, 8)
  assert.equal(stats.imageCount, 2)
  assert.equal(stats.wordCount, 32)
  assert.equal(stats.activeDays, 7)
  assert.equal(stats.firstDate, '2024-02-29')
  assert.equal(stats.durationDays, (Date.parse('2026-10-27') - Date.parse('2024-02-29')) / 86400000 + 1)
  assert.equal(stats.streak, 2)
  assert.equal(diaryStatistics(rows, '2026-10-28').streak, 2)
  assert.equal(diaryStatistics(rows, '2026-10-29').streak, 0)
  assert.equal(diaryStatistics([], '2026-10-27').durationDays, 0)
  const months = diaryYear(rows, 2026, '2026-10-27')
  assert.equal(months.length, 12)
  assert.equal(months[9].count, 4)
  assert.equal(months[9].days[4].day, 1) // Thursday: Sunday-first alignment.
  const today = months[9].days.find((day) => day.date === '2026-10-27')
  assert.equal(today.count, 2)
  assert.equal(today.words, 8)
  assert.equal(today.image, '/assets/another.svg')
  assert.equal(today.mood, '开心')
  assert.equal(today.weather, '晴')
  assert.equal(today.today, true)
  assert.equal(months[9].days.find((day) => day.date === '2026-10-28').future, true)
  assert.equal(diaryYear(rows, 2024)[1].days.filter((day) => !day.empty).length, 29)
  assert.equal(diaryYear(rows, 2025)[1].days.filter((day) => !day.empty).length, 28)
  const memories = diaryMemories(rows, '2026-10-27')
  assert.equal(memories[0].kind, 'anniversary')
  assert.equal(memories[0].date, '2025-10-27')
  assert.equal(memories[0].count, 2)
  assert.deepEqual(memories[0].dates, ['2025-10-27', '2024-10-27'])
  assert.ok(memories.every((memory) => !memory.revealed))
  const randomDates = memories.slice(1).map((memory) => memory.date)
  assert.equal(new Set(randomDates).size, randomDates.length)
  assert.ok(randomDates.every((date) => date < '2026-10-27' && date.slice(5) !== '10-27' && date >= '2024-02-29'))
  assert.deepEqual(diaryMemories(rows.slice().reverse(), '2026-10-27').map((memory) => memory.date), memories.map((memory) => memory.date))
  assert.equal(diaryMemories([], '2026-10-27')[0].empty, true)
  assert.equal(diaryMemories([entry('future', '2027-01-01')], '2026-10-27').length, 1)
  assert.equal(diaryMemories([entry('leap', '2024-02-29')], '2026-02-28')[0].empty, true)
  const cards = diaryFeed([entry('one', '2026-10-27', { time: '18:00', images: [1,2,3,4].map((id) => image(`photo${id}`)) }), entry('two', '2026-10-27'), entry('three', '2026-10-26')])
  assert.deepEqual(cards.map((card) => card.showDate), [true, false, true])
  assert.equal(cards[0].photos.length, 3)
  assert.equal(cards[0].extraPhotos, 1)
  assert.equal(cards[0].showTitle, false)
  // Exercise the real page bindings, including memory reveal and privacy filtering.
  let definition
  const routes = []
  Object.assign(globalThis, { Page: (options) => { definition = options }, wx: { navigateTo: (options) => routes.push(options.url), pageScrollTo() {}, showActionSheet: async () => ({ tapIndex: 1 }) } })
  const create = () => ({ ...definition, data: structuredClone(definition.data), setData(values, callback) { Object.assign(this.data, structuredClone(values)); if(callback)callback() } })
  const { diaryService } = require('../services/diary.ts')
  const originalList = diaryService.list
  diaryService.list = async () => rows
  require('../pages/diary/index.ts')
  const feed = create()
  feed.onLoad({ date: '2026-10-27' })
  await feed.refresh()
  assert.equal(feed.data.visible.length, 2)
  feed.clearFilters()
  assert.equal(feed.data.visible.length, 8)
  feed.setData({ memories })
  feed.revealMemory({ currentTarget: { dataset: { index: 1 } } })
  assert.equal(feed.data.memories[1].revealed, true)
  await feed.openMemory({ currentTarget: { dataset: { index: 1 } } })
  assert.equal(feed.data.selectedDate, memories[1].date)
  assert.ok(feed.data.visible.every((row) => row.date === memories[1].date))
  feed.revealMemory({ currentTarget: { dataset: { index: 0 } } })
  await feed.openMemory({ currentTarget: { dataset: { index: 0 } } })
  assert.equal(feed.data.memoryPickerOpen, true)
  assert.deepEqual(feed.data.memoryDates, ['2025-10-27', '2024-10-27'])
  feed.chooseMemoryDate({ currentTarget: { dataset: { date: '2024-10-27' } } })
  assert.equal(feed.data.selectedDate, '2024-10-27')
  assert.equal(feed.data.memoryPickerOpen, false)
  require('../pages/diary/calendar.ts')
  const calendar = create()
  calendar.onLoad()
  await calendar.refresh()
  calendar.changeMode({ currentTarget: { dataset: { mode: 'words' } } })
  assert.equal(calendar.data.mode, 'words')
  await calendar.selectDay({ currentTarget: { dataset: { date: '2026-10-27', count: 2 } } })
  assert.match(routes.at(-1), /index\?date=2026-10-27/)
  await calendar.selectDay({ currentTarget: { dataset: { date: '2026-10-28', count: 0 } } })
  assert.match(routes.at(-1), /edit\?date=2026-10-28/)
  require('../pages/diary/statistics.ts')
  const statistics = create()
  statistics.onLoad()
  await statistics.refresh()
  assert.equal(statistics.data.stats.total, 8)
  statistics.toggleReview()
  assert.equal(statistics.data.reviewOpen, true)
  assert.equal(statistics.data.yearMonths.length, 12)
  diaryService.list = originalList
  console.log('日记视图验证通过：统计与连续天数、闰年日历、图片/文字/心情/天气、Feed分组缩略图、稳定随机回忆、隐私过滤与导航')
}
run().catch((error) => { console.error(error); process.exitCode = 1 })
