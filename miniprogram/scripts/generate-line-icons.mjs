import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const require = createRequire(new URL('../../web-prototype/package.json', import.meta.url))
const { createElement } = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const lucide = require('lucide-react')
const sharp = require(process.argv[2] ? path.join(process.argv[2], 'sharp') : 'sharp')

const icons = {
  back: 'ChevronLeft', bell: 'Bell', book: 'BookOpen', calendar: 'CalendarDays',
  chart: 'ChartNoAxesColumn', check: 'CircleCheck', clipboard: 'ClipboardList',
  clock: 'Clock3', close: 'X', compose: 'SquarePen', down: 'ChevronDown',
  file: 'FileText', film: 'Film', filter: 'ListFilter', gift: 'Gift',
  heart: 'Heart', lock: 'Lock', menu: 'List', more: 'Ellipsis', plus: 'Plus',
  right: 'ChevronRight', search: 'Search', star: 'Star', task: 'Circle',
  trash: 'Trash2', wallet: 'Wallet', water: 'Droplet', walk: 'Footprints',
  room: 'Archive', trip: 'Map', breakfast: 'Croissant', audio: 'Headphones',
  home: 'House', profile: 'UserRound', gallery: 'Images', list: 'ListTodo',
  settings: 'Settings', chat: 'MessageCircle', people: 'UsersRound', invite: 'UserRoundPlus',
  tick: 'Check', bookmark: 'Bookmark', brush: 'Paintbrush', tag: 'Hash',
  undo: 'Undo2', indent: 'IndentIncrease', day: 'Calendar', info: 'Info', alert: 'CircleAlert',
  camera: 'Camera', image: 'Image', microphone: 'Mic', history: 'History',
  checklist: 'SquareCheck', shield: 'ShieldCheck',
}

const directory = path.join(root, 'assets/icons/line')
await fs.mkdir(directory, { recursive: true })
const sources = {}
for (const [name, component] of Object.entries(icons)) {
  if (!lucide[component]) throw new Error(`Unknown Lucide icon: ${component}`)
  const strokeWidth = ['back', 'down', 'right'].includes(name) ? 2 : 2.25
  const svg = renderToStaticMarkup(createElement(lucide[component], { color: '#2f2928', strokeWidth }))
    .replace(/ class="[^"]+"/, '')
  sources[name] = svg
  await sharp(Buffer.from(svg)).resize(96, 96).png().toFile(path.join(directory, `${name}.png`))
  if (['plus', 'compose', 'tick'].includes(name)) {
    await sharp(Buffer.from(svg.replace('#2f2928', '#ffffff'))).resize(96, 96).png().toFile(path.join(directory, `${name}-white.png`))
  }
}

await fs.copyFile(path.join(path.dirname(require.resolve('lucide-react/package.json')), 'LICENSE'), path.join(directory, 'LICENSE'))
await fs.writeFile(path.join(root, 'components/base/lp-icon/line-sources.ts'),
  '// Generated by scripts/generate-line-icons.mjs from the Web prototype’s Lucide dependency.\n'
    + 'export const LINE_ICON_SOURCES: Record<string, string> = ' + JSON.stringify(sources, null, 2) + '\n')
